  async getAccounts(_userId: string): Promise<Account[]> {
    // Return a copy to ensure determinism
    return JSON.parse(JSON.stringify(this.accounts))
  }

  async getTransactions(
    _userId: string,
    accountId: string,
    opts?: TransactionQueryOpts
  ): Promise<Transaction[]> {
    let filtered = this.transactions.filter(t => t.account_id === accountId)

    if (opts?.start_date) {
      filtered = filtered.filter(t => t.date >= opts.start_date!)
    }
    if (opts?.end_date) {
      filtered = filtered.filter(t => t.date <= opts.end_date!)
    }
    if (opts?.count) {
      filtered = filtered.slice(0, opts.count)
    }

    return JSON.parse(JSON.stringify(filtered))
  }

  async getBalance(_userId: string, accountId: string): Promise<Balance> {
    const account = this.accounts.find(a => a.id === accountId)
    if (!account) {
      throw new Error(`Account ${accountId} not found`)
    }

    return {
      account_id: accountId,
      current: account.balance_current,
      available: account.balance_available,
      currency: account.currency,
      last_updated: new Date().toISOString(),
    }
  }

