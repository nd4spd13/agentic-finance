/**
 * D3.2 — SimpleFIN paste-a-token connect flow for the desktop app.
 *
 * Mirrors `packages/cli/src/commands/connect.ts`'s `--provider simplefin`
 * path (SF6) almost exactly: claim the one-time setup token via
 * `@clad/simplefin-adapter`'s `claimSetupToken`, persist the resulting
 * access URL via the same `SqliteTokenStore` (`@clad/core`) the CLI uses, at
 * the same `simplefin_db` path (see `config.ts`'s `simplefin_db` field),
 * then warm the shared `SimpleFinCache` with one initial account fetch so
 * the very first `clad_get_balances` call doesn't have to burn a second
 * request against the Bridge's ~24 req/day shared quota.
 *
 * Unlike Plaid Link, there is no loopback server or browser handoff here at
 * all — the SimpleFIN Bridge protocol's setup token is generated by the user
 * on the Bridge's own site and pasted directly into `ConnectView.tsx`, so
 * this is a single request/response IPC call (`connect:simplefinConnect`),
 * not a long-running push-progress flow like `plaid-link-flow.ts`.
 *
 * Security: the setup token flows renderer -> main only (the user pastes
 * it); the resulting access URL is never returned to the renderer, logged,
 * or embedded in an error message anywhere in this file — only the
 * display-safe `SimpleFinAccountSummary`/error text below ever crosses back
 * over IPC. Every thrown error is described through `describeSimpleFinError`,
 * mirroring `connect.ts`'s own redaction discipline.
 */

import { randomUUID } from 'node:crypto'
import { getCladCore } from './clad-core.js'
import { getCladSimpleFinAdapter } from './simplefin-adapter.js'
import type { CladConfig } from './config.js'

/** Display-safe summary of a claimed SimpleFIN account — never the access URL or a raw un-namespaced account id. */
export interface SimpleFinAccountSummary {
  id: string
  name: string
  institution?: string
}

export interface SimpleFinConnectResult {
  ok: boolean
  itemId?: string
  accounts?: SimpleFinAccountSummary[]
  /** Set alongside `ok: true` when the item was saved but the initial account-summary fetch failed — non-fatal, matches `connect.ts`'s behavior (the credential is never lost just because this follow-up fetch failed). */
  warning?: string
  /** Display-safe (redacted where derived from stored/thrown data). Set when `ok: false`. */
  error?: string
}

/**
 * `'unavailable'` when the token-store passphrase isn't resolved yet — same
 * gate `missingPlaidPrereqs` uses for Plaid. Distinct from `'not-connected'`,
 * which means the passphrase works fine but no SimpleFIN item has been
 * saved yet.
 */
export type SimpleFinConnectionState = 'connected' | 'not-connected' | 'unavailable'

export interface SimpleFinConnectDeps {
  loadConfig: () => CladConfig
  /** Null when passphrase custody isn't resolved yet (e.g. CLI-migration prompt still pending). */
  getActivePassphrase: () => string | null
  /** Test-only seam forwarded to `claimSetupToken`/`fetchAccounts`; defaults to `globalThis.fetch` when omitted. Never set by real callers. */
  fetch?: typeof fetch
}

/** Read-only "connected/not connected" check — opens the token store just to list item metadata (never a token value), then closes it. */
export async function getSimpleFinConnectionState(
  deps: Pick<SimpleFinConnectDeps, 'loadConfig' | 'getActivePassphrase'>
): Promise<SimpleFinConnectionState> {
  const passphrase = deps.getActivePassphrase()
  if (!passphrase) return 'unavailable'

  const config = deps.loadConfig()
  const { SqliteTokenStore } = await getCladCore()

  let store: InstanceType<typeof SqliteTokenStore> | undefined
  try {
    store = new SqliteTokenStore({ dbPath: config.simplefin_db, passphrase })
    return store.listItems().length > 0 ? 'connected' : 'not-connected'
  } catch {
    // Wrong passphrase (shouldn't normally happen — Plaid and SimpleFIN
    // share the same custody-resolved passphrase) or any other open
    // failure: nothing safe to report beyond "can't tell right now".
    return 'unavailable'
  } finally {
    store?.close()
  }
}

/**
 * Claims a pasted SimpleFIN setup token and stores the resulting access URL.
 * Never throws — every failure path returns `{ ok: false, error }` so the
 * IPC handler in `main/index.ts` can stay a plain pass-through.
 */
export async function claimAndStoreSimpleFinToken(
  setupToken: string,
  deps: SimpleFinConnectDeps
): Promise<SimpleFinConnectResult> {
  const trimmed = setupToken.trim()
  if (!trimmed) {
    return { ok: false, error: 'A setup token is required.' }
  }

  const passphrase = deps.getActivePassphrase()
  if (!passphrase) {
    return {
      ok: false,
      error: 'The token-store passphrase is not resolved yet — finish the migration/setup prompt first.',
    }
  }

  const config = deps.loadConfig()
  const { SqliteTokenStore } = await getCladCore()

  let tokenStore: InstanceType<typeof SqliteTokenStore>
  try {
    tokenStore = new SqliteTokenStore({ dbPath: config.simplefin_db, passphrase })
  } catch (err) {
    return { ok: false, error: await describeSimpleFinError(err) }
  }

  try {
    const { claimSetupToken } = await getCladSimpleFinAdapter()
    // Never pass `trimmed`/`accessUrl` to anything but claimSetupToken and
    // tokenStore.saveItem/fetchAccounts below — no code path in this
    // function may interpolate either into a log or error string (mirrors
    // connect.ts's same invariant).
    const accessUrl = await claimSetupToken(trimmed, { fetch: deps.fetch })

    const itemId = `simplefin-${randomUUID()}`
    // The setup token is now consumed; the access URL is the only copy of
    // this credential that will ever exist. Persist it before attempting
    // anything else so a failure below (the account-summary prefetch) can
    // never lose it.
    tokenStore.saveItem({ itemId, institutionName: 'SimpleFIN Bridge', accessToken: accessUrl })

    let accounts: SimpleFinAccountSummary[] | undefined
    let warning: string | undefined
    try {
      accounts = await fetchInitialSimpleFinSummary(itemId, accessUrl, config.simplefin_db, deps.fetch)
    } catch (err) {
      warning =
        'Could not fetch an initial account summary yet: ' +
        (await describeSimpleFinError(err)) +
        ' Your SimpleFIN credentials were saved — this will retry automatically the next time data is requested.'
    }

    return { ok: true, itemId, accounts, warning }
  } catch (err) {
    return { ok: false, error: await describeSimpleFinError(err) }
  } finally {
    tokenStore.close()
  }
}

/**
 * Fetches this item's accounts once (widest protocol-allowed window,
 * `pending: true` — mirrors `connect.ts`'s `fetchInitialSimpleFinSummary`)
 * and records the result in the shared cache DB. Returns a summary
 * containing no secret material — never the access URL, never a raw
 * un-namespaced account id.
 */
async function fetchInitialSimpleFinSummary(
  itemId: string,
  accessUrl: string,
  dbPath: string,
  fetchImpl: typeof fetch | undefined
): Promise<SimpleFinAccountSummary[]> {
  const { fetchAccounts, mapAccountSet, MAX_WINDOW_SECONDS, SimpleFinCache } = await getCladSimpleFinAdapter()
  const cache = new SimpleFinCache({ dbPath })
  try {
    const nowSeconds = Math.floor(Date.now() / 1000)
    const accountSet = await fetchAccounts(accessUrl, {
      fetch: fetchImpl,
      startDate: Math.max(0, nowSeconds - MAX_WINDOW_SECONDS),
      endDate: nowSeconds,
      pending: true,
    })
    const { accounts, transactions } = mapAccountSet(accountSet)
    cache.recordFetch(itemId, accounts, transactions)
    return accounts.map((account) => ({
      id: account.id,
      name: account.name,
      institution: account.institution,
    }))
  } finally {
    cache.close()
  }
}

/**
 * Produces a user-facing error string for the SimpleFIN connect path.
 * `SimpleFinError` subclasses and `TokenStoreKeyError` already carry
 * pre-sanitized, secret-free messages; anything else is passed through
 * `redactSecrets` defensively — same discipline as `connect.ts`'s
 * `describeSimpleFinError`.
 */
async function describeSimpleFinError(error: unknown): Promise<string> {
  const { SimpleFinError } = await getCladSimpleFinAdapter()
  if (error instanceof SimpleFinError) return error.message
  const { TokenStoreKeyError, redactSecrets } = await getCladCore()
  if (error instanceof TokenStoreKeyError) return error.message
  if (error instanceof Error) return redactSecrets(error.message)
  return 'unknown error'
}
